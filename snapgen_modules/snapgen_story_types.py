def normalize_story_type(value):
    """Return a stable id from an id, Thai label, or legacy genre value."""
    raw = " ".join(str(value or "").split()).strip().casefold()
    if not raw or raw in {"auto", "automatic", "อัตโนมัติ", "อัตโนมัติตามบท", "อัตโนมัติตามเนื้อเรื่อง"}:
        return "auto"
    for story_type, label in STORY_TYPE_OPTIONS:
        if raw == label.casefold() or raw == story_type.casefold():
            return story_type
    aliases = {
        "นิทาน": "general_fairytale",
        "ทั่วไป": "general_fairytale",
        "พื้นบ้าน": "thai_folklore",
        "folklore": "thai_folklore",
        "ร่วมสมัย": "near_modern",
        "ย้อนยุคใกล้ปัจจุบัน": "near_modern",
        "ผี": "ghost_horror",
        "สยองขวัญ": "ghost_horror",
        "ghost": "ghost_horror",
        "วรรณคดี": "thai_literature",
        "วรรณคดีไทย": "thai_literature",
        "โบราณ": "ancient_thai",
        "ไทยโบราณ": "ancient_thai",
    }
    return aliases.get(raw, "auto")


def story_type_profile(value):
    story_type = normalize_story_type(value)
    return story_type, STORY_TYPE_PROFILES.get(story_type, {})


